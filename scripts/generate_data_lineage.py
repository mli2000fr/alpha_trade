"""Sprint S4 (A-019) — générateur automatique de la matrice data-lineage.

Produit ``doc/data_lineage_matrix.md`` à partir de la spécification interne
:data:`LINEAGE_SPEC` (single source of truth). Peut également mettre à jour
le bloc balisé ``provider_table_matrix`` de :file:`doc/service.md`.

Modes :

- défaut : régénère ``doc/data_lineage_matrix.md`` (écrit si différent).
- ``--check`` : exit 1 si le fichier diverge (utilisable en CI).
- ``--target service-md`` : ne touche qu'au bloc balisé de ``doc/service.md``.
- ``--verify-completeness`` : échoue si une table de
  ``database/sql/all_tables.py`` n'apparaît pas dans la spec.

Garanties d'idempotence : ordre stable, byte-identique entre deux runs
sans modification de la spec.

Usage :

.. code-block:: powershell

    python scripts/generate_data_lineage.py --check
    python scripts/generate_data_lineage.py --target service-md
"""
