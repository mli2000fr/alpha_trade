def _render_table(rows: list[LineageEntry]) -> str:
    headers = ("Table", "Producteur (CLI / module)", "Consommateurs",
               "Source upstream", "Provider actif", "Fréquence", "Criticité")
    lines = ["| " + " | ".join(headers) + " |",
             "|" + "|".join(["---"] * len(headers)) + "|"]
    for r in rows:
        lines.append("| " + " | ".join([
            r.table, r.producer, r.consumers, r.upstream,
            r.provider_active, r.frequency, r.criticality,
        ]) + " |")
    return "\n".join(lines)


def render_lineage_markdown(*, primary_provider: str = "eodhd") -> str:
    parts: list[str] = []
    parts.append("# Matrice Data Lineage — table ↔ producteur ↔ consommateurs (Phase 7.6)")
    parts.append("")
    parts.append(GENERATED_BANNER)
    parts.append("")
    parts.append(f"<!-- primary_provider: {primary_provider} -->")
    parts.append("")
    parts.append(HEADER_NOTES.rstrip())
    parts.append("")
    parts.append("---")
    parts.append("")
    parts.append("## Légende")
    parts.append("")
    parts.append("- **Fréquence** : `daily` / `intraday` / `on-event` / `manual`.")
    parts.append("- **Criticité** : `P1` (live trading bloque sans), `P2` (pipeline dégradé),")
    parts.append("  `P3` (analytics / audit uniquement).")
    parts.append("")
    parts.append("---")
    parts.append("")
    by_section: dict[str, list[LineageEntry]] = {s: [] for s in SECTIONS_ORDER}
    for entry in LINEAGE_SPEC:
        by_section[entry.section].append(entry)
    for section in SECTIONS_ORDER:
        rows = by_section[section]
        parts.append(f"## {section}")
        parts.append("")
        parts.append(_render_table(rows))
        parts.append("")
    parts.append(FOOTER_NOTES.rstrip())
    parts.append("")
    return "\n".join(parts)


def render_provider_block() -> str:
    headers = ("Provider", "Module(s) service", "Tables alimentées (DB)",
               "Mode appel", "Criticité")
    lines = [SERVICE_BLOCK_BEGIN,
             GENERATED_BANNER,
             "",
             "### 10. Matrice Provider → Tables alimentées",
             "",
             "| " + " | ".join(headers) + " |",
             "|" + "|".join(["---"] * len(headers)) + "|"]
    for p in PROVIDER_SPEC:
        tables = ", ".join(f"`{t}`" for t in p.tables)
        lines.append(f"| `{p.provider}` | `{p.service_module}` | {tables} | {p.mode} | {p.criticality} |")
    lines.append("")
    lines.append("> Matrice détaillée table-par-table : voir "
                 "[`doc/data_lineage_matrix.md`](data_lineage_matrix.md).")
    lines.append("")
    lines.append(SERVICE_BLOCK_END)
    return "\n".join(lines)


# ---------------------------------------------------------------------------
# Discovery / completeness
# ---------------------------------------------------------------------------

_TABLE_RE = re.compile(r"CREATE\s+TABLE\s+(?:IF\s+NOT\s+EXISTS\s+)?[\"`]?(\w+)[\"`]?",
                       re.IGNORECASE)


def discover_tables(path: Path = ALL_TABLES_PY) -> set[str]:
    if not path.exists():
        return set()
    txt = path.read_text(encoding="utf-8", errors="replace")
    return {m.group(1).lower() for m in _TABLE_RE.finditer(txt)}


def _spec_table_names() -> set[str]:
    names: set[str] = set()
    for entry in LINEAGE_SPEC:
        # Strip annotations like " *(...)*" or "(provider=...)"
        base = entry.table
        base = re.sub(r"\s*\*\(.*?\)\*", "", base)
        base = re.sub(r"\s*\(.*?\)", "", base)
        names.add(base.strip().lower())
    return names


# ---------------------------------------------------------------------------
# I/O helpers
# ---------------------------------------------------------------------------

def write_if_changed(path: Path, content: str) -> bool:
    """Écrit ``content`` dans ``path`` uniquement s'il y a une différence.

    Retourne ``True`` si une écriture a eu lieu, ``False`` sinon.
    """
    path.parent.mkdir(parents=True, exist_ok=True)
    existing = path.read_text(encoding="utf-8") if path.exists() else None
    if existing == content:
        return False
    path.write_text(content, encoding="utf-8")
    return True


def replace_block(text: str, *, begin: str, end: str, new_block: str) -> str:
    """Remplace ou insère un bloc balisé ``begin``..``end``."""
    pattern = re.compile(re.escape(begin) + r".*?" + re.escape(end), re.DOTALL)
    if pattern.search(text):
        return pattern.sub(new_block, text)
    sep = "" if text.endswith("\n") else "\n"
    return text + sep + "\n" + new_block + "\n"


# ---------------------------------------------------------------------------
# CLI
# ---------------------------------------------------------------------------

def _build_parser() -> argparse.ArgumentParser:
    p = argparse.ArgumentParser(description=__doc__.split("\n", maxsplit=1)[0])
    p.add_argument("--output", type=Path, default=DEFAULT_OUTPUT,
                   help=f"Fichier de sortie (défaut: {DEFAULT_OUTPUT.relative_to(ROOT)})")
    p.add_argument("--target", choices=("lineage", "service-md", "all"),
                   default="lineage",
                   help="Cible de génération : lineage (data_lineage_matrix.md), "
                        "service-md (bloc balisé de doc/service.md), all (les deux).")
    p.add_argument("--service-md-path", type=Path, default=SERVICE_MD,
                   help="Chemin de doc/service.md (override pour tests).")
    p.add_argument("--check", action="store_true",
                   help="N'écrit pas ; exit 1 si le fichier diverge.")
    p.add_argument("--verify-completeness", action="store_true",
                   help="Échoue si une table de all_tables.py n'apparaît pas dans la spec.")
    p.add_argument("--primary-provider", default="eodhd",
                   choices=("eodhd", "alpaca"),
                   help="Provider OHLCV primaire mentionné dans le bandeau.")
    p.add_argument("--log-level", default="INFO",
                   choices=("DEBUG", "INFO", "WARNING", "ERROR"))
    return p


def main(argv: list[str] | None = None) -> int:
    args = _build_parser().parse_args(argv)
    logging.basicConfig(level=getattr(logging, args.log_level), format="%(levelname)s %(message)s")

    if args.verify_completeness:
        sql_tables = discover_tables()
        spec_tables = _spec_table_names()
        missing = sorted(t for t in sql_tables if t not in spec_tables)
        if missing:
            LOGGER.error("Tables présentes dans all_tables.py mais absentes de LINEAGE_SPEC: %s",
                         ", ".join(missing))
            return 2

    targets = {"lineage", "service-md"} if args.target == "all" else {args.target}
    diverged = False

    if "lineage" in targets:
        content = render_lineage_markdown(primary_provider=args.primary_provider)
        if args.check:
            existing = args.output.read_text(encoding="utf-8") if args.output.exists() else ""
            if existing != content:
                LOGGER.error("data_lineage_matrix.md is out of date — re-run scripts/generate_data_lineage.py")
                diverged = True
            else:
                LOGGER.info("data_lineage_matrix.md up-to-date")
        else:
            changed = write_if_changed(args.output, content)
            LOGGER.info("data_lineage_matrix.md %s", "rewritten" if changed else "unchanged")

    if "service-md" in targets:
        block = render_provider_block()
        path = args.service_md_path
        existing_md = path.read_text(encoding="utf-8") if path.exists() else ""
        new_md = replace_block(existing_md, begin=SERVICE_BLOCK_BEGIN,
                               end=SERVICE_BLOCK_END, new_block=block)
        if args.check:
            if existing_md != new_md:
                LOGGER.error("doc/service.md provider block is out of date — re-run with --target service-md")
                diverged = True
            else:
                LOGGER.info("doc/service.md provider block up-to-date")
        else:
            changed = write_if_changed(path, new_md)
            LOGGER.info("doc/service.md provider block %s",
                        "rewritten" if changed else "unchanged")

    return 1 if diverged else 0


if __name__ == "__main__":  # pragma: no cover
    sys.exit(main())

