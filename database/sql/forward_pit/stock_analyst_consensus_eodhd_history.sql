CREATE TABLE IF NOT EXISTS alpha_trade.stock_analyst_consensus_eodhd_history (
  id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
  provider VARCHAR(16) NOT NULL DEFAULT 'eodhd',
  symbol VARCHAR(20) NOT NULL,
  snapshot_date DATE NOT NULL COMMENT 'Date New York de collecte, jamais date fiscale historique',
  fiscal_period_end DATE NOT NULL COMMENT 'Date déclarée par fournisseur, identité fiscale à qualifier',
  horizon_raw VARCHAR(8) NOT NULL,
  observed_at DATETIME(6) NOT NULL,
  available_at DATETIME(6) NOT NULL COMMENT 'Réception effective UTC, pas disponibilité historique reconstruite',
  run_id VARCHAR(96) NOT NULL,
  currency VARCHAR(8) DEFAULT NULL COMMENT 'Inconnue si absente du payload',
  eps_avg DOUBLE DEFAULT NULL,
  eps_low DOUBLE DEFAULT NULL,
  eps_high DOUBLE DEFAULT NULL,
  eps_analyst_count INT DEFAULT NULL,
  eps_growth DOUBLE DEFAULT NULL,
  eps_year_ago DOUBLE DEFAULT NULL,
  revenue_avg DOUBLE DEFAULT NULL,
  revenue_low DOUBLE DEFAULT NULL,
  revenue_high DOUBLE DEFAULT NULL,
  revenue_analyst_count INT DEFAULT NULL,
  revenue_growth DOUBLE DEFAULT NULL,
  revenue_year_ago DOUBLE DEFAULT NULL,
  eps_current DOUBLE DEFAULT NULL,
  eps_7d_ago DOUBLE DEFAULT NULL,
  eps_30d_ago DOUBLE DEFAULT NULL,
  eps_60d_ago DOUBLE DEFAULT NULL,
  eps_90d_ago DOUBLE DEFAULT NULL,
  revisions_up_7d INT DEFAULT NULL,
  revisions_up_30d INT DEFAULT NULL,
  revisions_down_7d INT DEFAULT NULL,
  revisions_down_30d INT DEFAULT NULL,
  provider_growth DOUBLE DEFAULT NULL,
  fiscal_identity_qualified BOOLEAN NOT NULL DEFAULT FALSE,
  units_qualified BOOLEAN NOT NULL DEFAULT FALSE,
  historical_pit_qualified BOOLEAN NOT NULL DEFAULT FALSE,
  qualification_status VARCHAR(32) NOT NULL DEFAULT 'RESEARCH_ONLY',
  raw_hash CHAR(64) NOT NULL,
  raw_payload_json LONGTEXT NOT NULL,
  parser_version VARCHAR(16) NOT NULL DEFAULT 'eodhd_v1',
  ingestion_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
  PRIMARY KEY (id),
  UNIQUE KEY uq_eodhd_consensus_daily (provider,symbol,snapshot_date,fiscal_period_end,horizon_raw),
  KEY ix_eodhd_consensus_pit (symbol,available_at),
  KEY ix_eodhd_consensus_run (run_id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
