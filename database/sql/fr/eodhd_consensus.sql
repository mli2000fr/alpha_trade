CREATE TABLE IF NOT EXISTS alpha_trade_fr.eodhd_consensus_raw_payloads (
  id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
  provider VARCHAR(16) NOT NULL DEFAULT 'eodhd',
  symbol VARCHAR(20) NOT NULL,
  observation_day DATE NOT NULL,
  run_id VARCHAR(96) NOT NULL,
  observed_at DATETIME(6) NOT NULL,
  available_at DATETIME(6) NULL,
  raw_hash CHAR(64) NOT NULL,
  payload_json LONGTEXT NOT NULL,
  parse_status VARCHAR(16) NOT NULL,
  normalized_rows INT NOT NULL DEFAULT 0,
  KEY ix_fr_consensus_daily (symbol,observation_day,parse_status),
  KEY ix_fr_consensus_raw_run (run_id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS alpha_trade_fr.stock_analyst_consensus_eodhd_history (
  id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
  provider VARCHAR(16) NOT NULL DEFAULT 'eodhd',
  market_code VARCHAR(16) NOT NULL,
  symbol VARCHAR(20) NOT NULL,
  isin CHAR(12) NOT NULL,
  reference_sha256 CHAR(64) NOT NULL,
  raw_payload_id BIGINT UNSIGNED NOT NULL,
  snapshot_date DATE NOT NULL COMMENT 'Date Paris de collecte, jamais date fiscale historique',
  fiscal_period_end DATE NOT NULL,
  horizon_raw VARCHAR(8) NOT NULL,
  observed_at DATETIME(6) NOT NULL,
  available_at DATETIME(6) NULL COMMENT 'Confirmation après commit, UTC',
  run_id VARCHAR(96) NOT NULL,
  currency VARCHAR(8) NULL,
  eps_avg DOUBLE NULL, eps_low DOUBLE NULL, eps_high DOUBLE NULL, eps_analyst_count INT NULL,
  eps_growth DOUBLE NULL, eps_year_ago DOUBLE NULL,
  revenue_avg DOUBLE NULL, revenue_low DOUBLE NULL, revenue_high DOUBLE NULL, revenue_analyst_count INT NULL,
  revenue_growth DOUBLE NULL, revenue_year_ago DOUBLE NULL,
  eps_current DOUBLE NULL, eps_7d_ago DOUBLE NULL, eps_30d_ago DOUBLE NULL,
  eps_60d_ago DOUBLE NULL, eps_90d_ago DOUBLE NULL,
  revisions_up_7d INT NULL, revisions_up_30d INT NULL,
  revisions_down_7d INT NULL, revisions_down_30d INT NULL,
  provider_growth DOUBLE NULL,
  fiscal_identity_qualified BOOLEAN NOT NULL DEFAULT FALSE,
  units_qualified BOOLEAN NOT NULL DEFAULT FALSE,
  historical_pit_qualified BOOLEAN NOT NULL DEFAULT FALSE,
  qualification_status VARCHAR(32) NOT NULL DEFAULT 'RESEARCH_ONLY',
  raw_hash CHAR(64) NOT NULL,
  raw_payload_json LONGTEXT NOT NULL,
  parser_version VARCHAR(16) NOT NULL,
  ingestion_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
  UNIQUE KEY uq_eodhd_consensus_daily (provider,symbol,snapshot_date,fiscal_period_end,horizon_raw),
  KEY ix_fr_consensus_pit (symbol,available_at),
  KEY ix_fr_consensus_run (run_id),
  CONSTRAINT fk_fr_consensus_raw FOREIGN KEY (raw_payload_id)
    REFERENCES alpha_trade_fr.eodhd_consensus_raw_payloads(id) ON DELETE RESTRICT
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
