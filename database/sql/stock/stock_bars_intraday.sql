CREATE TABLE IF NOT EXISTS alpha_trade.stock_bars_intraday (
    symbol VARCHAR(20) NOT NULL,
    bar_timestamp DATETIME(6) NOT NULL COMMENT 'Start of interval in UTC',
    interval_code VARCHAR(3) NOT NULL DEFAULT '5m',
    data_source VARCHAR(32) NOT NULL DEFAULT 'eodhd_intraday',
    provider VARCHAR(16) NOT NULL DEFAULT 'eodhd' COMMENT 'alpaca or eodhd; data_source also distinguishes IEX/SIP',
    market_code VARCHAR(16) NOT NULL DEFAULT 'US_EQ',
    provider_symbol VARCHAR(40) NOT NULL,
    bar_end_timestamp DATETIME(6) NOT NULL COMMENT 'Exclusive interval end UTC',
    trade_date DATE NOT NULL COMMENT 'Calendar date America/New_York, not shifted to next session',
    session_tag VARCHAR(20) NOT NULL COMMENT 'pre_market / regular / post_market / non_trading_day',
    open DECIMAL(20,8) NOT NULL,
    high DECIMAL(20,8) NOT NULL,
    low DECIMAL(20,8) NOT NULL,
    close DECIMAL(20,8) NOT NULL,
    volume BIGINT UNSIGNED NOT NULL,
    data_adjustment VARCHAR(16) NOT NULL DEFAULT 'raw',
    is_filled TINYINT(1) NOT NULL DEFAULT 0,
    observed_at DATETIME(6) NOT NULL COMMENT 'Actual provider retrieval UTC, not historical availability',
    payload_hash CHAR(64) NOT NULL,
    run_id VARCHAR(128) NOT NULL,
    ingested_at TIMESTAMP(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
    last_updated TIMESTAMP(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6) ON UPDATE CURRENT_TIMESTAMP(6),
    PRIMARY KEY (symbol,bar_timestamp,interval_code,data_source),
    KEY idx_intraday_date_interval (trade_date,interval_code),
    KEY idx_intraday_timestamp (bar_timestamp),
    KEY idx_intraday_run (run_id),
    CONSTRAINT chk_intraday_interval CHECK (interval_code IN ('1m','5m','1h')),
    CONSTRAINT chk_intraday_raw CHECK (data_adjustment='raw'),
    CONSTRAINT chk_intraday_us CHECK (market_code='US_EQ'),
    CONSTRAINT chk_intraday_prices CHECK (open>0 AND close>0 AND low>0 AND high>=open AND high>=close AND low<=open AND low<=close),
    CONSTRAINT chk_intraday_end CHECK (bar_end_timestamp>bar_timestamp)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
